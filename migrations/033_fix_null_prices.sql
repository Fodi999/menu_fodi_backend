-- Проблема: Items созданные до pricing-рефакторинга имеют NULL в current_price_per_unit
-- Решение: Устанавливаем 0 для всех NULL цен (пользователь сможет добавить позже)

-- Обновляем NULL цены на 0 (чтобы избежать ошибок при расчётах)
UPDATE user_fridge_items
SET current_price_per_unit = 0
WHERE current_price_per_unit IS NULL;

-- Проверка: сколько записей обновлено
SELECT COUNT(*) as fixed_items
FROM user_fridge_items
WHERE current_price_per_unit = 0;

